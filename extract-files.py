#!/usr/bin/env python
# Copy the blobs in proprietary-files.txt into vendor/huawei/y220/proprietary
# and write vendor/huawei/y220/y220-vendor-blobs.mk.
#
# Sources (see proprietary-files.txt):
#   Y220_SYSTEM  the CM7 vendor tree's proprietary dir (Y220 GB stock)
#   Y330_SYSTEM  the extracted Y330-U01 B121 system

import os
import shutil
import sys

TOP = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
SOURCES = {
    "y220": os.environ.get(
        "Y220_SYSTEM", "/mnt/fuentes/cm7/vendor/huawei/y220/proprietary"),
    "y330": os.environ.get(
        "Y330_SYSTEM", "/mnt/fuentes/references/y330-stock-B121/system"),
}
LIST = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    "proprietary-files.txt")
VENDOR = os.path.join(TOP, "vendor/huawei/y220")
OUT = os.path.join(VENDOR, "proprietary")
BLOBS = os.path.join(VENDOR, "y220-vendor-blobs.mk")

HEADER = """# Generated by device/huawei/y220/extract-files.py from
# device/huawei/y220/proprietary-files.txt. Do not edit.

PRODUCT_COPY_FILES += \\
"""


def entries():
    for line in open(LIST):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(":")
        if len(parts) not in (2, 3) or parts[0] not in SOURCES:
            sys.exit("bad line in %s: %s" % (LIST, line))
        src, path = parts[0], parts[1]
        dest = parts[2] if len(parts) == 3 else path
        yield src, path, dest


def main():
    for name, root in SOURCES.items():
        if not os.path.isdir(root):
            sys.exit("missing %s system: %s" % (name, root))

    if os.path.isdir(OUT):
        shutil.rmtree(OUT)

    dests = []
    for src, path, dest in entries():
        from_path = os.path.join(SOURCES[src], path)
        if not os.path.isfile(from_path):
            sys.exit("missing %s:%s" % (src, path))
        to_path = os.path.join(OUT, dest)
        if not os.path.isdir(os.path.dirname(to_path)):
            os.makedirs(os.path.dirname(to_path))
        # New mtime: a blob swapped for an older file must still be newer
        # than the copy in out/, or make keeps the old one.
        shutil.copy(from_path, to_path)
        dests.append(dest)

    with open(BLOBS, "w") as f:
        f.write(HEADER)
        lines = ["    vendor/huawei/y220/proprietary/%s:system/%s" % (d, d)
                 for d in sorted(dests)]
        f.write(" \\\n".join(lines) + "\n")

    print("%d files" % len(dests))


if __name__ == "__main__":
    main()
